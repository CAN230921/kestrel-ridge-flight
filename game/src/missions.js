export function computeWindVector(mission, time) {
  const base = mission.windBase ?? [0, 0, 0];
  const gust = mission.windGust ?? 0;
  const g1 = Math.sin(time * 0.7) * Math.cos(time * 0.31) * gust;
  const g2 = Math.cos(time * 0.53) * gust * 0.5;
  return [base[0] + g2, 0, base[2] + g1];
}
